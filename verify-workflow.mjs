import assert from 'node:assert/strict';
import { chromium } from 'playwright';
import fs from 'node:fs/promises';
const base='http://localhost:4173';
async function api(path,data,method='POST'){const r=await fetch(base+path,{method,headers:{'Content-Type':'application/json'},body:data?JSON.stringify(data):undefined});const j=await r.json();if(!r.ok)throw new Error(JSON.stringify(j));return j;}
const applicant=await api('/api/applicants',{name:'功能检查临时申请人',occupation:'设计师',visaType:'O1B'});
let browser;
try{
  browser=await chromium.launch({headless:true,executablePath:'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe'});
  const page=await browser.newPage({viewport:{width:1440,height:1000}});
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  await page.goto(base);
  await page.getByRole('button',{name:applicant.name,exact:true}).click();
  await page.getByRole('button',{name:'网页截图',exact:true}).last().click();
  await page.getByRole('button',{name:'试用样例文章'}).click();
  await page.getByRole('button',{name:'生成图片描述',exact:true}).waitFor({timeout:60000});
  await page.getByRole('button',{name:'生成图片描述',exact:true}).click();
  const generate=page.getByRole('button',{name:'生成全部图片的中英文描述'});
  assert.equal(await generate.isDisabled(),true);
  await page.getByLabel('材料类别',{exact:true}).selectOption('Media Coverage');
  assert.equal(await generate.isDisabled(),true,'presence must be selected');
  await page.getByLabel('申请人是否在画面中？',{exact:true}).selectOption('no');
  await page.getByLabel('背景备注').fill('这是虚构的功能测试文章，申请人未出现在图片中。');
  await generate.click();
  await page.waitForFunction(()=>document.querySelector('#description-zh')?.value.length>0,{},{timeout:90000});
  const en=await page.locator('#description-text').inputValue();
  const zh=await page.locator('#description-zh').inputValue();
  assert.match(zh,/[\u4e00-\u9fff]/);assert.match(en,/[a-zA-Z]/);
  await fs.mkdir('.cache/verification',{recursive:true});
  await page.screenshot({path:'.cache/verification/description-zh.png',fullPage:true});
  await page.getByRole('button',{name:'保存',exact:true}).click();
  await page.getByRole('button',{name:`查看 ${applicant.name} 的已保存材料`}).waitFor();
  let state=await api('/api/state',undefined,'GET');
  let evidence=state.evidence.find(e=>e.applicantId===applicant.id);
  assert.equal(evidence.descriptionZh,zh);assert.equal(evidence.description,en);assert.equal(evidence.applicantInImage,'no');
  await page.getByRole('button',{name:`查看 ${applicant.name} 的已保存材料`}).click();
  await page.locator('.evidence-card').click();
  await page.getByLabel('已保存的中文描述').fill(zh+'（修改测试）');
  await page.getByRole('button',{name:'保存修改',exact:true}).click();
  await page.waitForFunction(()=>document.querySelector('dialog button.button.primary')?.disabled===true);
  await page.getByRole('button',{name:'关闭',exact:true}).click();
  page.once('dialog',d=>d.dismiss());
  await page.getByRole('button',{name:'删除材料：studio-journal.png',exact:true}).click();
  assert.equal(await page.locator('.evidence-card').count(),1);
  page.once('dialog',d=>d.accept());
  await page.getByRole('button',{name:'删除材料：studio-journal.png',exact:true}).click();
  await page.waitForFunction(()=>!document.querySelector('.evidence-card'));
  state=await api('/api/state',undefined,'GET');assert.equal(state.evidence.some(e=>e.id===evidence.id),false);
  await api('/api/evidence',{...evidence,savedId:undefined});
  page.once('dialog',d=>d.dismiss());
  await page.getByRole('button',{name:'删除申请人',exact:true}).click();
  assert.equal(await page.getByRole('heading',{name:applicant.name,exact:true}).count(),1);
  page.once('dialog',d=>d.accept());
  await page.getByRole('button',{name:'删除申请人',exact:true}).click();
  await page.getByRole('heading',{name:'申请人',exact:true}).waitFor();
  state=await api('/api/state',undefined,'GET');
  assert.equal(state.applicants.some(a=>a.id===applicant.id),false);assert.equal(state.evidence.some(e=>e.applicantId===applicant.id),false);
  await page.setViewportSize({width:390,height:844});
  await page.goto(base+'/#description');
  await page.getByRole('heading',{name:'图片描述',exact:true}).waitFor();
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
  assert.deepEqual(errors,[]);
  console.log('PASS: required presence, live bilingual generation, bilingual persistence/edit, cancelled and confirmed image deletion, cancelled and confirmed cascade applicant deletion, mobile width, no page errors.');
}finally{
  await browser?.close();
  const state=await api('/api/state',undefined,'GET');
  if(state.applicants.some(a=>a.id===applicant.id))await api('/api/applicants',{id:applicant.id},'DELETE');
}
